import { chromium, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

const url = process.env.PL_DEMO_URL || 'http://127.0.0.1:8010'
const destination = new URL('../../docs/images/', import.meta.url).pathname
await mkdir(destination, { recursive: true })
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, deviceScaleFactor: 1 })
  await page.goto(url)
  await expect(page.getByRole('button', { name: 'Explore this match' })).toBeVisible()
  await page.screenshot({ path: destination + 'discover.png', animations: 'disabled' })
  await page.goto(url + '/#graph')
  await expect(page.getByText('21 NODES · 20 EDGES')).toBeVisible()
  await page.screenshot({ path: destination + 'demo-graph.png', fullPage: true, animations: 'disabled' })
  await page.getByLabel('Search graph player').fill('allison')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.getByText('Choose a player from the closest roster matches below.')).toBeVisible()
  await page.screenshot({ path: destination + 'player-search.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Overview', exact: true }).click()
  await page.getByLabel('Explore club').selectOption({ label: 'Liverpool' })
  await expect(page.getByRole('heading', { name: 'Liverpool', exact: true })).toBeVisible()
  await page.screenshot({ path: destination + 'demo-club.png', fullPage: true, animations: 'disabled' })
  await page.getByLabel('Filter fixtures').fill('Liverpool')
  await page.getByRole('button', { name: /Liverpool versus Bournemouth/ }).first().click()
  await expect(page.getByText(/NODES.*EDGES/)).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Fixture connections' })).toBeVisible()
  await page.screenshot({ path: destination + 'demo-match.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Football analyst', exact: true }).click()
  await page.getByLabel('Football statistics question').fill("Compare Aston Villa and Liverpool's season statistics.")
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByText('65 points', { exact: false })).toBeVisible()
  await page.waitForTimeout(700)
  await page.screenshot({ path: destination + 'demo-analysis.png', fullPage: true, animations: 'disabled' })
  await page.goto(url + '/#evidence')
  await expect(page.getByLabel('Evidence question')).toBeEnabled({ timeout: 120000 })
  await page.getByLabel('Evidence season').selectOption('2022-23')
  await page.getByLabel('Evidence question').fill('Liverpool home match against Bournemouth')
  await page.getByRole('button', { name: 'Find evidence', exact: true }).click()
  await expect(page.getByText('Verified records', { exact: true })).toBeVisible({ timeout: 120000 })
  await page.screenshot({ path: destination + 'evidence.png', animations: 'disabled' })
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 })
  await mobile.goto(url)
  await expect(mobile.getByRole('button', { name: 'Explore this match' })).toBeVisible()
  await mobile.screenshot({ path: destination + 'discover-mobile.png', animations: 'disabled' })
  await mobile.goto(url + '/#graph')
  await expect(mobile.getByText('21 NODES · 20 EDGES')).toBeVisible()
  await mobile.screenshot({ path: destination + 'demo-graph-mobile.png', fullPage: true, animations: 'disabled' })
  await mobile.getByRole('button', { name: 'Navigation', exact: true }).click()
  await mobile.getByRole('button', { name: 'Football analyst', exact: true }).click()
  await mobile.getByLabel('Football statistics question').fill("Compare Aston Villa and Liverpool's season statistics.")
  await mobile.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(mobile.getByText('65 points', { exact: false })).toBeVisible()
  await mobile.waitForTimeout(700)
  await mobile.screenshot({ path: destination + 'demo-mobile.png', fullPage: true, animations: 'disabled' })
} finally {
  await browser.close()
}
