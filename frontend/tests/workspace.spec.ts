import { test, expect } from '@playwright/test'
const fixtures = [
  { id: 'first', date: '2025-08-15', home_team: 'Liverpool', away_team: 'Bournemouth', home_score: 4, away_score: 2, gameweek: 1 },
  { id: 'second', date: '2025-08-22', home_team: 'Aston Villa', away_team: 'Liverpool', home_score: 1, away_score: 1, gameweek: 2 },
]
test.beforeEach(async ({ page }) => {
  await page.route('**/api/matches', r => r.fulfill({ json: fixtures }))
  await page.route('**/api/graph/overview', r => r.fulfill({ json: { nodes: [], edges: [] } }))
})
test('discovery spotlight switches real records and opens selected match', async ({ page }) => {
  await page.route('**/api/graph/match/second', r => r.fulfill({ json: { nodes: [{ id: 'second', name: 'Aston Villa vs Liverpool', type: 'Match', home: 'Aston Villa', away: 'Liverpool' }], edges: [] } }))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Football. Connected.' })).toBeVisible()
  const spotlight = page.getByLabel('Match spotlight')
  await expect(spotlight).toContainText('Bournemouth')
  await page.getByRole('button', { name: 'Next spotlight match' }).click()
  await expect(spotlight).toContainText('Aston Villa')
  await expect(spotlight).toContainText('2 / 2 fixtures')
  await spotlight.getByRole('button', { name: 'Aston Villa', exact: true }).click()
  await expect(spotlight).toContainText('1 / 1 fixtures')
  await expect(page.getByRole('button', { name: 'Next spotlight match' })).toBeDisabled()
  await page.getByRole('button', { name: 'Explore this match' }).click()
  await expect(page).toHaveURL(/#graph$/)
  await expect(page.getByRole('heading', { name: 'Fixture connections' })).toBeVisible()
  await expect(page.getByText('1 NODES · 0 EDGES')).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('heading', { name: 'Football. Connected.' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
test('quick switch supports keyboard filtering, empty results and direct routes', async ({ page }) => {
  await page.route('**/api/evidence/status', r => r.fulfill({ status: 503, json: { status: 'not_ready', seasons: [], primary_season: '2025-26' } }))
  await page.goto('/')
  await page.getByRole('button', { name: 'Open quick switch' }).click()
  const dialog = page.getByRole('dialog')
  const search = page.getByLabel('Jump to your next question')
  await expect(search).toBeFocused()
  await search.fill('no-such-tool')
  await expect(dialog).toContainText('No tools match')
  await search.fill('records')
  await search.press('Enter')
  await expect(dialog).not.toBeVisible()
  await expect(page).toHaveURL(/#evidence$/)
  await expect(page.getByRole('heading', { name: 'Find the record behind the question' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Find the record behind the question' })).toBeVisible()
  await page.keyboard.press('Control+k')
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
})
test('mobile navigation contains focus and reduced motion removes animation', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  const menu = page.getByRole('button', { name: 'Navigation', exact: true })
  if (await menu.isVisible()) {
    await menu.click()
    await expect(page.getByRole('complementary', { name: 'Workspace navigation' }).getByRole('button', { name: 'Close navigation', exact: true })).toBeFocused()
    await page.keyboard.press('Shift+Tab')
    expect(await page.evaluate(() => !!document.activeElement?.closest('.app-sidebar'))).toBe(true)
    await page.keyboard.press('Escape')
    await expect(menu).toBeFocused()
    await expect(menu).toHaveAttribute('aria-expanded', 'false')
  }
  expect(await page.locator('.workspace-content').evaluate(el => getComputedStyle(el).animationName)).toBe('none')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
